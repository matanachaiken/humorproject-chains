import Image from "next/image";
import type { RunStepView } from "@/lib/runs";

// What one step produced. Used on the Generate and Media tabs.
export default function StepOutput({ step }: { step: RunStepView }) {
  return (
    <>
      {step.outputImage && (
        <Image
          src={step.outputImage}
          alt={`Generated by the step "${step.name}"`}
          width={1024}
          height={1024}
          sizes="(max-width: 640px) 100vw, 400px"
          className="mt-2 h-auto w-full max-w-sm rounded-lg border border-line"
        />
      )}
      {step.outputText && <p className="mt-2 whitespace-pre-wrap text-sm leading-relaxed">{step.outputText}</p>}
      {step.error && <p className="mt-2 text-sm text-bad">{step.error}</p>}
    </>
  );
}
